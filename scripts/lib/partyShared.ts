/**
 * Builds the server copy of Party's category engine: src/ files flattened into supabase/functions/_shared/party/,
 * with their relative imports rewritten, plus a slim dataset. Pure (no Node APIs): the CLI (scripts/syncPartyShared.ts)
 * reads and writes the files, and src/lib/party/sharedDrift.test.ts compares the committed copies with this output.
 */

/** Where the copies go, relative to the repo root. */
export const SHARED_DIR = 'supabase/functions/_shared/party'

/** Engine source files (repo-relative) and the flat file name each one gets in SHARED_DIR. */
export const ENGINE_SOURCES: readonly { from: string; to: string }[] = [
  { from: 'src/lib/party/categories.ts', to: 'categories.ts' },
  { from: 'src/lib/party/types.ts', to: 'types.ts' },
  { from: 'src/config/partyConfig.ts', to: 'partyConfig.ts' },
  { from: 'src/types/pokemon.ts', to: 'pokemon.ts' },
  { from: 'src/lib/rng.ts', to: 'rng.ts' },
]

/** The dataset the engine reads, and the fields it needs (id is part of every Pokemon entry; the rest are read by the engine). */
export const DATASET_SOURCE = 'src/data/pokemon.json'
export const DATASET_TARGET = 'pokemon.json'
export const DATASET_FIELDS = [
  'id',
  'dexNumber',
  'name',
  'type1',
  'type2',
  'generation',
  'height',
  'weight',
  'color',
  'evolutionStage',
  'abilities',
  'eggGroups',
  'formCategory',
] as const

export const HEADER = '// Generated by npm run party:sync from src/ — do not edit\n'

/** Resolves a relative import (`../rng.ts`) against the importing file's directory, as a repo-relative path. */
function resolveImport(fromFile: string, specifier: string): string {
  const parts = fromFile.split('/').slice(0, -1)
  for (const seg of specifier.split('/')) {
    if (seg === '.' || seg === '') continue
    if (seg === '..') parts.pop()
    else parts.push(seg)
  }
  return parts.join('/')
}

/** Rewrites every relative import to point at the flat copy. Throws on an import the copy does not contain. */
export function rewriteImports(source: string, fromFile: string, targets: ReadonlyMap<string, string>): string {
  return source.replace(/(\bfrom\s+|\bimport\s*\(\s*)(['"])(\.{1,2}\/[^'"]+)\2/g, (_match, lead: string, quote: string, spec: string) => {
    const resolved = resolveImport(fromFile, spec)
    const target = targets.get(resolved)
    if (!target) throw new Error(`${fromFile} imports ${spec}, which is not in the server copy list`)
    return `${lead}${quote}./${target}${quote}`
  })
}

/** The slim dataset: only DATASET_FIELDS, one entry per line, so diffs stay readable. */
export function slimDataset(json: string): string {
  const entries = JSON.parse(json) as Record<string, unknown>[]
  const lines = entries.map((entry) => {
    const slim: Record<string, unknown> = {}
    for (const field of DATASET_FIELDS) {
      if (!(field in entry)) throw new Error(`dataset entry ${String(entry.name)} has no ${field}`)
      slim[field] = entry[field]
    }
    return `  ${JSON.stringify(slim)}`
  })
  return `[\n${lines.join(',\n')}\n]\n`
}

/**
 * Every file that SHARED_DIR should contain, keyed by repo-relative path, with its exact content.
 * `read` returns a repo-relative file's text.
 */
export function buildSharedFiles(read: (path: string) => string): Map<string, string> {
  const targets = new Map(ENGINE_SOURCES.map((s) => [s.from, s.to]))
  const out = new Map<string, string>()
  for (const { from, to } of ENGINE_SOURCES) {
    out.set(`${SHARED_DIR}/${to}`, HEADER + rewriteImports(read(from), from, targets))
  }
  out.set(`${SHARED_DIR}/${DATASET_TARGET}`, slimDataset(read(DATASET_SOURCE)))
  return out
}
